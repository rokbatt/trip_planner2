-- Supabase 대시보드 → SQL Editor 에 붙여넣고 실행하세요. 여러 번 실행해도 안전합니다.
--
-- 여러 예약 사이트에서 후보를 모아 채팅 링크로 공유 → STAY 보드에 담기까지는 되는데,
-- 그 다음 "가격을 서로 비교하면서 하나씩 지워나가는" 과정이 몽실이 안에서 안 됐음(따로
-- 메모하고 지도를 눈대중으로 봐야 했음). 그 과정을 후보 카드 안에서 바로 하도록:
--
-- price_note   자유 텍스트 가격 메모(예: "1박 15만원", "3박 총 45만원"). 통화·환산 없이
--              사용자가 채팅에서 본 걸 그대로 옮겨 적는 용도라 구조화하지 않음.
-- is_excluded  소거법으로 "이건 아니다"라고 표시한 후보. 삭제는 아니라서 언제든 복원 가능 —
--              카드 목록에서 흐리게 표시되고 맨 아래로 정렬됨.
-- ============================================================

alter table if exists places add column if not exists price_note text;
alter table if exists places add column if not exists is_excluded boolean not null default false;
