-- 여행지 도착 정보 (공항 + 도착 시각) — DAY 1이 숙소가 아니라 공항에서 시작함을 반영
-- Supabase 대시보드 → SQL Editor 에 붙여넣고 실행하세요.
-- 여러 번 실행해도 안전(idempotent)합니다.
--
-- 왜 필요한가
--   ROUTE의 DAY 1은 지금까지 "숙소에서 09:00 출발"로 고정돼 있었음. 실제로는
--   비행기가 도착하는 시각 이후에야 하루가 시작되고, 그 시작점도 숙소가 아니라
--   공항임. 이 정보가 없으면 AI 일정 짜기도 "숙소에서부터 하루 종일 자유롭다"고
--   착각해 비행기 도착 전 시간대에 일정을 넣거나, 공항→숙소 이동을 아예 무시함.
--
--   공항의 정확한 좌표까지는 담지 않는다(원칙 3-1 — 실측 안 된 좌표를 지어내
--   지도에 찍으면 왜곡). 이름(자유 입력)과 도착 시각만 저장해 AI 프롬프트의
--   맥락으로만 쓰고, 지도 위에 가상의 공항 핀을 그리지는 않는다.
-- ============================================================

alter table if exists trip_destinations add column if not exists arrival_airport text;
alter table if exists trip_destinations add column if not exists arrival_time text; -- 'HH:MM', 24시간

