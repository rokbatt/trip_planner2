-- 왜 필요한가
--   ROUTE의 하루는 지금까지 "장소는 하루에 한 번만 방문"으로만 짜여 있었음. 실제로는
--   점심에 숙소에 짐 두러 잠깐 들렀다 다시 나가는 것처럼, 같은 숙소를 하루에 두 번 이상
--   들르는 경우가 흔함. 이런 "재방문" 스탑은 place_id 없이(=지도에 직접 찍은 지점과 같은
--   방식) 그 순간 기준 숙소의 좌표로 저장되고, 이 컬럼이 그 방문 목적(예: "짐 두기")을
--   담아 TIMELINE/ROUTE가 일반 장소 카드가 아니라 전용 스타일로 구분해 보여줄 수 있게 한다.
-- ============================================================

alter table if exists route_stops add column if not exists stop_purpose text;

