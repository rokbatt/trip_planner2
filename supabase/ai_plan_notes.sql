-- AI 일정 짜기 — 여행 니즈/요청사항 (자유 텍스트)
-- Supabase 대시보드 → SQL Editor 에 붙여넣고 실행하세요.
-- 여러 번 실행해도 안전(idempotent)합니다.
--
-- 왜 필요한가
--   지금까지 "AI 일정 짜기"는 영업시간·인기 동선·이동 효율이라는 고정된 규칙만 따라서
--   짰음 — 이 여행이 "휴양 위주로 여유롭게"인지 "맛집 투어 중심"인지, 혹은 "1일차는
--   밤 늦게 도착하니 그냥 쉬는 날로" 같은 사용자의 실제 의도를 반영할 방법이 아예 없었다.
--   이 텍스트를 매 프롬프트에 그대로 넣어서 AI가 사용자 의도를 최우선으로 반영하게 한다.
--   (원칙 3-1 — 우리가 구조화/해석하지 않고 사용자가 쓴 그대로만 전달, 지어내지 않음)
--
--   여행지(trip_destinations) 단위로 저장 — 한 번 써두면 "AI 일정 짜기"를 다시 눌러도
--   유지된다. 실제 여행지 행이 없는(마이그레이션 전) 레거시 단일 여행지 트립은
--   arrival_airport 등과 마찬가지로 이 기능 대상에서 제외된다.
-- ============================================================

alter table if exists trip_destinations add column if not exists ai_plan_notes text;

